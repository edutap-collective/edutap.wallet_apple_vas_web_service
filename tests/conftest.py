@pytest.fixture
def role_search_path(bare_engine):
    """Return a callable that sets the connecting role's `search_path`.

    `ALTER ROLE ... SET search_path` and not a connection-level `SET`: this is
    the form Ansible uses, it is what a DDL role actually arrives with, and it
    reaches the connection Alembic opens for itself inside `env.py` -- which a
    `SET` on the test's own connection would not.

    Reset on teardown, because the setting outlives the database objects the
    test dropped.
    """
    role = bare_engine.url.username

    def set_to(search_path: str | None) -> None:
        if search_path is None:
            return
        with bare_engine.begin() as connection:
            connection.execute(sa.text(f'ALTER ROLE "{role}" SET search_path TO {search_path}'))

    yield set_to

    with bare_engine.begin() as connection:
        connection.execute(sa.text(f'ALTER ROLE "{role}" RESET search_path'))


