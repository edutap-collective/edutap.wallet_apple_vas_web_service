DSN_VARIABLE = "WALLET_APPLE_VAS_WEB_SERVICE_TEST_DSN"

ROOT = Path(__file__).resolve().parent.parent


def _alembic_config(dsn: str):
    """Alembic pointed at the test database rather than at the developer's own.

    The URL is handed over through `sqlalchemy.url` rather than through the
    environment, because `env.py` reads the URL from the Alembic config when it
    carries one and only falls back to the package's `DatabaseSettings`
    otherwise. Setting the environment instead would leave the developer's own
    `EDUTAP_WALLET_APPLE_VAS_WEB_SERVICE_DB_*` variables in play for every
    field the test did not override.
    """
    from alembic.config import Config

    config = Config(str(ROOT / "alembic.ini"))
    config.set_main_option("sqlalchemy.url", dsn)
    return config


def _drop_owned_schema(engine: sa.Engine) -> None:
    """Return the database to the state a fresh deployment finds it in."""
    with engine.begin() as connection:
        connection.execute(sa.schema.DropSchema(SCHEMA, cascade=True, if_exists=True))


@pytest.fixture(scope="module")
def engine():
    """An engine against a throwaway database; skips when none is configured.

    The tables come from `alembic upgrade head`, not from
    `metadata.create_all()`. They are two different DDL paths, and only one of
    them runs in operation: `create_all` would have created the sequence
    `last_update_tag` is drawn from as a side effect of the metadata carrying
    it, and would therefore have kept the whole suite green against a baseline
    migration that omits it -- which is exactly what an autogenerated baseline
    does (see `migrations/versions/0001_initial.py`). Every database-backed
    test in this suite now runs against what a deployment actually gets.
    """
    dsn = os.environ.get(DSN_VARIABLE)
    if not dsn:
        pytest.skip(f"{DSN_VARIABLE} is not set")
    from alembic import command

    engine = sa.create_engine(dsn)
    _drop_owned_schema(engine)
    command.upgrade(_alembic_config(dsn), "head")
    yield engine
    _drop_owned_schema(engine)
    engine.dispose()


